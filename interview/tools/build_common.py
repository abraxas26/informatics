random.seed(11)
out = []
for c in CATS:
    rx = re.compile(c["pat"])
    hits = [q for q in qs if rx.search(q[2])]
    seen, ex = set(), []
    random.shuffle(hits)
    for u, dept, q, a in hits:
        key = re.sub(r"\s+", "", q)[:40]
        if key in seen or not (10 <= len(q) <= 160):
            continue
        seen.add(key)
        ex.append({"univ": u, "dept": dept, "q": q})
        if len(ex) >= 24:
            break
    out.append({**c,
                "count": len(hits),
                "share": round(len(hits) / max(1, len(qs)) * 100, 1),
                "examples": sorted(ex, key=lambda x: (x["univ"], x["dept"]))})

json.dump({"totalQuestions": len(qs), "categories": out},
          open(OUT, "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
print("total questions:", len(qs))
for c in out:
    print("%-22s %5d (%4.1f%%)  예시 %d" % (c["title"], c["count"], c["share"], len(c["examples"])))
